[CmdletBinding()]
param(
    [Parameter()]
    [string]$RepositoryRoot,

    [Parameter()]
    [switch]$VerifyOnly
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'ProductIdentity.ps1')

if ([string]::IsNullOrWhiteSpace($RepositoryRoot)) {
    $RepositoryRoot = Split-Path -Parent $PSScriptRoot
}

function ConvertTo-GeneratedStringLiteralContent {
    param([Parameter(Mandatory)][string]$Value)
    return $Value.Replace('\', '\\').Replace('"', '\"')
}

function Write-OrVerifyGeneratedFile {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$Content
    )

    $encoding = [System.Text.UTF8Encoding]::new($false)
    $expectedBytes = $encoding.GetBytes($Content)

    if ($VerifyOnly) {
        if (-not [System.IO.File]::Exists($Path)) {
            throw "Generated product identity file is missing: $Path"
        }
        $actualBytes = [System.IO.File]::ReadAllBytes($Path)
        if ([Convert]::ToBase64String($actualBytes) -cne [Convert]::ToBase64String($expectedBytes)) {
            throw "Generated product identity file is out of date: $Path"
        }
        return
    }

    [System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($Path)) | Out-Null
    [System.IO.File]::WriteAllBytes($Path, $expectedBytes)
}

function Expand-GeneratedTemplate {
    param(
        [Parameter(Mandatory)][string]$Template,
        [Parameter(Mandatory)][psobject]$Identity
    )

    $content = $Template
    foreach ($property in $Identity.PSObject.Properties) {
        $escapedValue = ConvertTo-GeneratedStringLiteralContent $property.Value
        $token = '{' + $property.Name + '}'
        $content = $content.Replace($token, $escapedValue)
    }
    return $content.Replace("`r`n", "`n").TrimEnd("`r", "`n") + "`n"
}

$root = [System.IO.Path]::GetFullPath($RepositoryRoot)
$identity = Get-ProductIdentity -Path (Join-Path $root 'eng\ProductIdentity.props')

$mainCSharp = Expand-GeneratedTemplate -Identity $identity -Template @'
// <auto-generated />
// Generated from eng/ProductIdentity.props by scripts/Update-ProductIdentityGeneratedFiles.ps1.

namespace BaiduBatchTransfer.App.Branding;

internal static class ProductIdentity
{
    internal const string DisplayName = "{ProductDisplayName}";
    internal const string Description = "{ProductDescription}";
    internal const string MainAssemblyBaseName = "{ProductMainAssemblyName}";
    internal const string MainExecutableName = "{ProductMainExecutableName}";
    internal const string MainAssemblyName = "{ProductMainDllName}";
    internal const string LegacyAssemblyName = "{ProductLegacyAssemblyName}";
    internal const string LegacyExecutableName = "{ProductLegacyExecutableName}";
    internal const string PackageId = "{ProductPackageId}";
    internal const string DataDirectoryName = "{ProductDataDirectoryName}";
    internal const string LicenseProductId = "{ProductLicenseProductId}";
}
'@

$launcherCSharp = Expand-GeneratedTemplate -Identity $identity -Template @'
// <auto-generated />
// Generated from eng/ProductIdentity.props by scripts/Update-ProductIdentityGeneratedFiles.ps1.

namespace BaiduBatchTransfer.LegacyLauncher;

internal static class ProductIdentity
{
    internal const string DisplayName = "{ProductDisplayName}";
    internal const string MainExecutableName = "{ProductMainExecutableName}";
    internal const string LegacyExecutableName = "{ProductLegacyExecutableName}";
}
'@

$go = Expand-GeneratedTemplate -Identity $identity -Template @'
// Code generated from eng/ProductIdentity.props by scripts/Update-ProductIdentityGeneratedFiles.ps1. DO NOT EDIT.

package release

const (
	productDisplayName          = "{ProductDisplayName}"
	productDescription          = "{ProductDescription}"
	productMainAssemblyName     = "{ProductMainAssemblyName}"
	productMainExecutableName   = "{ProductMainExecutableName}"
	productMainDLLName          = "{ProductMainDllName}"
	productLegacyAssemblyName   = "{ProductLegacyAssemblyName}"
	productLegacyExecutableName = "{ProductLegacyExecutableName}"
	productPackageID            = "{ProductPackageId}"
	productDataDirectoryName    = "{ProductDataDirectoryName}"
	productLicenseProductID     = "{ProductLicenseProductId}"
)
'@

Write-OrVerifyGeneratedFile -Path (Join-Path $root 'src\BaiduBatchTransfer.App\Branding\ProductIdentity.Generated.cs') -Content $mainCSharp
Write-OrVerifyGeneratedFile -Path (Join-Path $root 'src\BaiduBatchTransfer.LegacyLauncher\ProductIdentity.Generated.cs') -Content $launcherCSharp
Write-OrVerifyGeneratedFile -Path (Join-Path $root 'services\ota_admin\internal\release\product_identity_generated.go') -Content $go

if ($VerifyOnly) {
    Write-Output 'Product identity generated files are current.'
}
