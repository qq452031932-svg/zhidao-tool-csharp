[CmdletBinding()]
param(
    [Parameter()]
    [string]$RepositoryRoot,

    [Parameter()]
    [switch]$VerifyOnly
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'ProductIdentity.ps1')

if ([string]::IsNullOrWhiteSpace($RepositoryRoot)) {
    $RepositoryRoot = Split-Path -Parent $PSScriptRoot
}

function ConvertTo-CSharpStringLiteralContent {
    param([Parameter(Mandatory)][string]$Value)

    $builder = [System.Text.StringBuilder]::new()
    foreach ($character in $Value.ToCharArray()) {
        $code = [int]$character
        if ($code -eq 0x22) { [void]$builder.Append('\"') }
        elseif ($code -eq 0x5c) { [void]$builder.Append('\\') }
        elseif ($code -eq 0x00) { [void]$builder.Append('\0') }
        elseif ($code -eq 0x07) { [void]$builder.Append('\a') }
        elseif ($code -eq 0x08) { [void]$builder.Append('\b') }
        elseif ($code -eq 0x0c) { [void]$builder.Append('\f') }
        elseif ($code -eq 0x0a) { [void]$builder.Append('\n') }
        elseif ($code -eq 0x0d) { [void]$builder.Append('\r') }
        elseif ($code -eq 0x09) { [void]$builder.Append('\t') }
        elseif ($code -eq 0x0b) { [void]$builder.Append('\v') }
        elseif (($code -lt 0x20) -or ($code -ge 0x7f -and $code -le 0x9f) -or $code -eq 0x2028 -or $code -eq 0x2029) {
            [void]$builder.Append(('\u{0:x4}' -f $code))
        }
        else { [void]$builder.Append($character) }
    }
    return $builder.ToString()
}

